CREATE TABLE `patient_medical_history` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `patient_profile_id` INTEGER NOT NULL,
  `title` VARCHAR(255) NOT NULL,
  `discovered_at` DATE NULL,
  `description` TEXT NULL,
  `surgery_history` TEXT NULL,
  `family_history` TEXT NULL,
  `source` VARCHAR(30) NOT NULL DEFAULT 'PATIENT',
  `reported_by` INTEGER NULL,
  `confirmation_status` VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  `confirmed_by` INTEGER NULL,
  `confirmed_at` DATETIME(0) NULL,
  `deleted_at` DATETIME(0) NULL,
  `created_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  `updated_at` DATETIME(0) NOT NULL DEFAULT CURRENT_TIMESTAMP(0),
  INDEX `idx_patient_history_profile` (`patient_profile_id`, `deleted_at`, `created_at`),
  INDEX `idx_patient_history_confirmer` (`confirmed_by`),
  INDEX `idx_patient_history_reporter` (`reported_by`),
  CONSTRAINT `fk_patient_history_profile` FOREIGN KEY (`patient_profile_id`) REFERENCES `patient_profiles` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_patient_history_confirmer` FOREIGN KEY (`confirmed_by`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_patient_history_reporter` FOREIGN KEY (`reported_by`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

